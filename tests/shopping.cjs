const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const vm=require('node:vm');
const exportsObject={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/shopping.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:exportsObject,URL});
const {retailerUrl,normalizeShoppingItems,shoppingTotal}=exportsObject;
const url='https://www.amazon.com/dp/B0DGD34RRT';
const item={category:'sofa',quantity:1,price:499.99,priceQuote:'$499.99',productUrl:url};
assert.equal(retailerUrl('https://amazon.com.evil.example/dp/B0DGD34RRT'),null);
assert.equal(retailerUrl('javascript:alert(1)'),null);
assert.equal(retailerUrl('https://amazon.com/s?k=sofa'),null);
assert.equal(normalizeShoppingItems([item],[])[0].price,null);
assert.equal(normalizeShoppingItems([{...item,price:199}], [url])[0].price,null);
assert.equal(normalizeShoppingItems([{...item,priceQuote:'$399.99 - $499.99'}], [url])[0].price,null);
assert.equal(normalizeShoppingItems([{...item,price:1299.99,priceQuote:'USD 1,299.99'}], [url])[0].price,1299.99);
assert.equal(normalizeShoppingItems([null,item], [url]).length,1);
const items=normalizeShoppingItems([item,{...item,category:'armchair',quantity:2,price:100,priceQuote:'$100.00'},{category:'rug',price:null},{...item,included:false}], [url]);
assert.equal(shoppingTotal(items).total,699.99);
assert.equal(shoppingTotal(items).missing,1);
assert.equal(shoppingTotal(items).count,3);
console.log('PASS: source-bound prices, unsafe links, price evidence, quantities, missing prices and exclusions');
